    /// <summary>Generates the sources for <paramref name="model"/>. <c>MessageKey</c> is always emitted.</summary>
    public static ImmutableArray<GeneratedSource> Emit(LocalizationModel model) =>
        [
            new(Namespace + ".MessageKey.g.cs", EmitMessageKey()),
            new(Namespace + ".L.g.cs", EmitMessages(model)),
            new(Namespace + ".MessageCatalog.g.cs", EmitCatalog(model)),
