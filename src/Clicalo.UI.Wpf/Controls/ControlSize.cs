namespace Clicalo.UI.Wpf.Controls;

/// <summary>The three control heights of direction C (D12, <see cref="Theming.Generated.ControlHeight"/>).</summary>
public enum ControlSize
{
    /// <summary>44: icon buttons, chips, keys, text buttons and inner segments.</summary>
    Small,

    /// <summary>52: fields, list rows, switch rows and a segmented control with its track.</summary>
    Medium,

    /// <summary>64: option cards, navigation rows and the tiles of the fixed row.</summary>
    Large,
}
